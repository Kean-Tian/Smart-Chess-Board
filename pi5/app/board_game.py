def fen_board(fen):
    board = {}
    for rank, row in zip(range(7, -1, -1), fen.split()[0].split("/")):
        file = 0
        for token in row:
            if token.isdigit():
                file += int(token)
            else:
                board[rank * 8 + file] = token
                file += 1
    return board


def occupancy(board):
    return sum(1 << square for square in board)


def square(name):
    if len(name) != 2 or name[0] not in "abcdefgh" or name[1] not in "12345678":
        raise ValueError("Invalid square")
    return (int(name[1]) - 1) * 8 + ord(name[0]) - ord("a")


def expected_occupancy(fen, legal_move):
    """Only call with a move already generated by the authoritative rules engine."""
    board = fen_board(fen)
    source, target = square(legal_move[:2]), square(legal_move[2:4])
    piece = board.pop(source)
    if piece.lower() == "p" and source % 8 != target % 8 and target not in board:
        # En passant removes the pawn behind the destination.
        board.pop(target - 8 if piece == "P" else target + 8)
    if piece.lower() == "k" and abs(source % 8 - target % 8) == 2:
        rank = source // 8
        rook_source = rank * 8 + (7 if target > source else 0)
        rook_target = source + (1 if target > source else -1)
        board[rook_target] = board.pop(rook_source)
    board[target] = piece
    return occupancy(board)


class PhysicalGame:
    def __init__(self, game, link, report=print, engine=None, computer="b", movetime_ms=500, coaching=None):
        self.game, self.link, self.report = game, link, report
        self.mask = None
        self.initialized = False
        self.restore_required = False
        self.pending = None
        self.engine = engine
        self.computer = computer
        self.movetime_ms = movetime_ms
        self.computer_move = None
        self.opponent_failed = False
        self.coaching = coaching

    @property
    def opponent_name(self):
        return getattr(self.engine, "name", "Computer")

    def maybe_computer_turn(self):
        if (self.engine is None or not self.initialized or self.restore_required or
                self.computer_move or self.opponent_failed or self.game.fen().split()[1] != self.computer or
                self.mask != occupancy(fen_board(self.game.fen()))):
            return
        status = self.game.status()
        if status and status != "Check.":
            return
        try:
            move = self.engine.choose(self.game, self.movetime_ms)
        except OpenRouterError as exc:
            self.opponent_failed = True
            self.report(str(exc))
            self.report("Position preserved. Enter retry to request the AI move again.")
            return
        if move is None:
            return
        if move not in self.game.legal_moves():
            raise EngineError("Computer move failed authoritative rules validation")
        self.computer_move = move
        self.link.request(f"MARK {move[:2]} {move[2:4]} LEGAL")
        self.report(f"{self.opponent_name} > {move}. Execute this move on the physical board.")

    def on_board(self, mask):
        self.mask = mask
        if mask == occupancy(fen_board(self.game.fen())):
            self.initialized = True
            self.restore_required = False
            self.pending = None
            self.report("Board synchronized.")
            if self.coaching:
                self.coaching.show_hint()
        elif self.pending:
            self.try_move(self.pending)

    def try_move(self, move):
        if not re.fullmatch(r"[a-h][1-8][a-h][1-8][qrbn]?", move):
            self.report("Use a UCI move such as e2e4 or e7e8q.")
            return False
        if not self.initialized or self.restore_required or self.mask is None:
            self.report("Restore the physical board to the logical position first.")
            return False
        if self.engine is not None and self.game.fen().split()[1] == self.computer:
            wanted = self.computer_move
            if wanted and len(move) == 4 and wanted[:4] == move:
                move = wanted  # Use the engine's explicit promotion choice.
            if not wanted or move != wanted:
                self.restore_required = True
                self.report("Restore the board, then follow the requested computer move.")
                return False
        legal = self.game.legal_moves()
        choices = [m for m in legal if m == move or (len(move) == 4 and m[:4] == move)]
        if not choices:
            self.pending = None
            self.restore_required = True
            self.link.request(f"MARK {move[:2]} {move[2:4]} ILLEGAL")
            self.report("Illegal move. Logical state unchanged; restore the board.")
            return False
        if len(choices) != 1:
            self.pending = None
            self.report("Promotion choice required: enter commit e7e8q (or r/b/n).")
            return False
        uci = choices[0]
        if expected_occupancy(self.game.fen(), uci) != self.mask:
            self.pending = move
            self.report("Waiting for the complete physical move.")
            return False
        if not self.game.play(uci):
            raise RuntimeError("Rules engine rejected its generated legal move")
        self.pending = None
        self.computer_move = None
        self.link.request(f"MARK {uci[:2]} {uci[2:4]} LEGAL")
        self.report(self.game.board_text())
        if self.game.status():
            self.report(self.game.status())
        if self.coaching:
            self.coaching.show_hint()
        return True


def run(args):
    coaching_requested = (getattr(args, "coaching", False) or
                          getattr(args, "coach_white", None) is not None or
                          getattr(args, "coach_black", None) is not None)
    settings = configure_coaching(args) if coaching_requested else None
    if coaching_requested and settings is None:
        return 0
    with ExitStack() as stack:
        engine = stack.enter_context(create_opponent(args)) if args.mode == "pvc" and not coaching_requested else None
        game = stack.enter_context(Game())
        coaching = stack.enter_context(CoachingSession(game, settings, lambda: create_openrouter(args.model))) if coaching_requested else None
        link = stack.enter_context(ScbLink.open(args.port))
        manager = PhysicalGame(game, link, engine=engine, computer=args.computer[0],
                               movetime_ms=args.movetime, coaching=coaching)
        if engine:
            print(f"Opponent: {engine.name}. Computer plays {args.computer}.")
        if coaching:
            print("AI Coaching: two human players. Hints do not move pieces.")
            coaching.show_settings()
        for attempt in range(30):
            try:
                link.request("SCAN")
                break
            except DeviceError as exc:
                if str(exc) != "NOT_READY" or attempt == 29:
                    raise
                time.sleep(0.05)
        print(game.board_text())
        print("Arrange the standard initial position. Commands: board, commit <uci>, retry, quit.")
        if coaching:
            print("Coaching commands: coach white on/off, coach black on/off, coach, hint.")
        while True:
            try:
                frame = link.events.get(timeout=0.05)
                if frame.kind == "BOARD":
                    manager.on_board(int(frame.payload, 16))
                elif frame.kind == "EVENT" and frame.payload.startswith("MOVE "):
                    manager.try_move(frame.payload.split()[1])
                elif frame.kind in {"FAULT", "EVENT"}:
                    print(frame.kind, frame.payload)
            except queue.Empty:
                pass
            manager.maybe_computer_turn()
            if select.select([sys.stdin], [], [], 0)[0]:
                line = sys.stdin.readline().strip().lower()
                if not line or line == "quit":
                    break
                if line == "board":
                    print(game.board_text())
                elif coaching and (line == "hint" or line.split()[0] == "coach"):
                    if (not manager.initialized or manager.restore_required or
                            manager.mask != occupancy(fen_board(game.fen()))):
                        print("Synchronize the physical board before requesting or changing coaching.")
                    else:
                        coaching.handle_command(line)
                elif line == "retry":
                    manager.opponent_failed = False
                    manager.maybe_computer_turn()
                elif line.startswith("commit "):
                    manager.try_move(line.split(maxsplit=1)[1])
                else:
                    print("Use board, commit <uci>, retry, or quit.")
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description="Pi rules console with ESP32-S3 sensor input")
    parser.add_argument("--port", default="/dev/ttyACM0")
    parser.add_argument("--mode", choices=["pvp", "pvc"], default="pvp")
    add_opponent_arguments(parser)
    add_coaching_arguments(parser)
    return run(parser.parse_args(argv))


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (KeyboardInterrupt, DeviceError, EngineError, OpenRouterError, TimeoutError, ValueError, OSError) as exc:
        print(exc, file=sys.stderr)
        raise SystemExit(1)
